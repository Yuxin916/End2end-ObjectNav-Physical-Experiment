    # ================ for weight different digit positions in coordinate output ========================
    def _build_coordinate_position_kinds(self) -> Optional[List[str]]:
        "Build coordinate token pattern for all coordinate-based auxiliary losses."
        if len(self.coordinate_digit_token_ids) != 10:
            logger.warning('Coordinate pattern disabled: digit token ids are incomplete.')
            return None
        if self.coordinate_comma_token_id is None:
            logger.warning('Coordinate pattern disabled: comma token id is missing.')
            return None
        if self.coordinate_space_token_id is None:
            logger.warning('Coordinate pattern disabled: space token id is missing.')
            return None

        pattern = ['d', 'd', 'd', ',', ' ', 'd', 'd', 'd']
        return pattern

    def _get_coordinate_token_tensors(self, device: torch.device):
        cache_key = str(device)
        cached = self._coordinate_token_cache.get(cache_key)
        if cached is None:
            digit_ids = torch.as_tensor(self.coordinate_digit_token_ids, dtype=torch.long, device=device)
            comma_id = torch.as_tensor(int(self.coordinate_comma_token_id), dtype=torch.long, device=device)
            space_id = torch.as_tensor(int(self.coordinate_space_token_id), dtype=torch.long, device=device)
            pattern_pos = torch.arange(len(self._coordinate_position_kinds), dtype=torch.long, device=device)
            subset_ids = torch.cat([digit_ids, comma_id.view(1), space_id.view(1)], dim=0)
            cached = {
                'digit_ids': digit_ids,
                'comma_id': comma_id,
                'space_id': space_id,
                'pattern_pos': pattern_pos,
                'subset_ids': subset_ids,
            }
            self._coordinate_token_cache[cache_key] = cached
        return cached

    def _build_coordinate_position_index(self, shift_labels: torch.LongTensor) -> Optional[torch.LongTensor]:
        if self._coordinate_position_kinds is None:
            return None

        batch_size, seq_len = shift_labels.shape
        pattern_len = len(self._coordinate_position_kinds)
        if seq_len < pattern_len:
            return None

        cache = self._get_coordinate_token_tensors(shift_labels.device)
        digit_token_ids = cache['digit_ids']
        comma_token_id = cache['comma_id']
        space_token_id = cache['space_id']
        pattern_pos = cache['pattern_pos']

        pos_index = torch.full(
            (batch_size, seq_len),
            -1,
            dtype=torch.long,
            device=shift_labels.device,
        )

        # Vectorized pattern matching for ddd, ddd over the full [B, S] labels tensor.
        is_digit = (shift_labels.unsqueeze(-1) == digit_token_ids.view(1, 1, -1)).any(dim=-1)
        is_comma = shift_labels == comma_token_id
        is_space = shift_labels == space_token_id

        start_mask = (
            is_digit[:, 0:seq_len - 7]
            & is_digit[:, 1:seq_len - 6]
            & is_digit[:, 2:seq_len - 5]
            & is_comma[:, 3:seq_len - 4]
            & is_space[:, 4:seq_len - 3]
            & is_digit[:, 5:seq_len - 2]
            & is_digit[:, 6:seq_len - 1]
            & is_digit[:, 7:seq_len]
        )

        starts = torch.nonzero(start_mask, as_tuple=False)
        if starts.numel() == 0:
            return pos_index

        span_positions = starts[:, 1].unsqueeze(1) + pattern_pos.unsqueeze(0)
        batch_positions = starts[:, 0].unsqueeze(1).expand_as(span_positions)
        span_values = pattern_pos.unsqueeze(0).expand_as(span_positions)
        pos_index[batch_positions, span_positions] = span_values

        return pos_index

    # ================  for number-aware loss function ================ 
    def _token_ids_to_digit_values(self, token_ids: torch.LongTensor) -> torch.LongTensor:
        cache = self._get_coordinate_token_tensors(token_ids.device)
        digit_ids = cache['digit_ids']
        matches = token_ids.unsqueeze(-1) == digit_ids.view(*([1] * token_ids.dim()), -1)
        has_match = matches.any(dim=-1)
        digit_values = matches.to(dtype=torch.long).argmax(dim=-1)
        return torch.where(has_match, digit_values, torch.full_like(digit_values, -1))

    def _compute_numeric_aux_loss(
            self,
            shift_logits: torch.FloatTensor,
            shift_labels: torch.LongTensor,
    ) -> Optional[torch.FloatTensor]:
        if not self.use_numeric_aux_loss:
            return None
        if self.lambda_num <= 0:
            return None
        if len(self.coordinate_digit_token_ids) != 10:
            return None
        if self.coordinate_comma_token_id is None or self.coordinate_space_token_id is None:
            return None

        pred_xy, target_xy = self._extract_soft_pred_and_target_coordinates(shift_logits, shift_labels)
        if pred_xy is None or target_xy is None:
            return None
        pred_xy_norm = pred_xy / 999.0
        target_xy_norm = target_xy / 999.0
        return F.l1_loss(pred_xy_norm, target_xy_norm, reduction='mean')

    def _extract_coordinate_digit_logits_and_targets(
            self,
            shift_logits: torch.FloatTensor,
            shift_labels: torch.LongTensor,
    ) -> Tuple[Optional[torch.FloatTensor], Optional[torch.FloatTensor]]:
        if len(self.coordinate_digit_token_ids) != 10:
            return None, None
        if self.coordinate_comma_token_id is None or self.coordinate_space_token_id is None:
            return None, None

        pos_index = self._build_coordinate_position_index(shift_labels)
        if pos_index is None:
            return None, None

        start_mask = pos_index == 0
        if not torch.any(start_mask):
            return None, None

        starts = torch.nonzero(start_mask, as_tuple=False)
        batch_indices = starts[:, 0]
        start_indices = starts[:, 1]
        digit_offsets = torch.as_tensor([0, 1, 2, 5, 6, 7], dtype=torch.long, device=shift_labels.device)
        gather_positions = start_indices.unsqueeze(1) + digit_offsets.unsqueeze(0)

        gathered_logits = shift_logits[batch_indices.unsqueeze(1), gather_positions]  # [N, 6, V]
        digit_token_ids = torch.as_tensor(self.coordinate_digit_token_ids, dtype=torch.long, device=shift_logits.device)
        digit_logits = gathered_logits[..., digit_token_ids]  # [N, 6, 10]

        gathered_labels = shift_labels[batch_indices.unsqueeze(1), gather_positions]
        target_digits = self._token_ids_to_digit_values(gathered_labels)
        valid = (target_digits >= 0).all(dim=1)
        if not torch.any(valid):
            return None, None

        target_digits = target_digits[valid].to(dtype=torch.float32)
        target_x = 100.0 * target_digits[:, 0] + 10.0 * target_digits[:, 1] + target_digits[:, 2]
        target_y = 100.0 * target_digits[:, 3] + 10.0 * target_digits[:, 4] + target_digits[:, 5]
        target_xy = torch.stack([target_x, target_y], dim=-1).to(device=shift_logits.device)
        return digit_logits[valid], target_xy

    def _extract_soft_pred_and_target_coordinates(
            self,
            shift_logits: torch.FloatTensor,
            shift_labels: torch.LongTensor,
    ) -> Tuple[Optional[torch.FloatTensor], Optional[torch.FloatTensor]]:
        """Return differentiable predicted xy and decoded target xy for all valid coordinate spans."""
        digit_logits, target_xy = self._extract_coordinate_digit_logits_and_targets(shift_logits, shift_labels)
        if digit_logits is None or target_xy is None:
            return None, None

        # Parse soft coordinates with expectation over digit logits (fully differentiable).
        digit_probs = torch.softmax(digit_logits, dim=-1)
        digit_values = torch.arange(10, dtype=digit_probs.dtype, device=digit_probs.device)
        expected_digits = (digit_probs * digit_values.view(1, 1, -1)).sum(dim=-1)  # [N, 6]

        pred_x = 100.0 * expected_digits[:, 0] + 10.0 * expected_digits[:, 1] + expected_digits[:, 2]
        pred_y = 100.0 * expected_digits[:, 3] + 10.0 * expected_digits[:, 4] + expected_digits[:, 5]
        pred_xy = torch.stack([pred_x, pred_y], dim=-1)

        return pred_xy, target_xy.to(dtype=pred_xy.dtype)

    def _get_coordinate_value_tensors(self, device: torch.device):
        cache_key = str(device)
        cached = self._coordinate_value_cache.get(cache_key)
        if cached is None:
            values = torch.arange(1000, dtype=torch.long, device=device)
            cached = {
                'values_long': values,
                'values_float': values.to(dtype=torch.float32),
                'hundreds': values // 100,
                'tens': (values // 10) % 10,
                'ones': values % 10,
            }
            self._coordinate_value_cache[cache_key] = cached
        return cached

    def _gaussian_axis_targets(
            self,
            target_values: torch.FloatTensor,
            axis_values: torch.FloatTensor,
            sigma: float,
    ) -> torch.FloatTensor:
        diff = (axis_values.view(1, -1) - target_values.float().view(-1, 1)) / float(sigma)
        probs = torch.exp(-0.5 * diff.pow(2))
        return probs / probs.sum(dim=-1, keepdim=True).clamp_min(1e-12)

    def _compute_coord_dist_aux_loss(
            self,
            shift_logits: torch.FloatTensor,
            shift_labels: torch.LongTensor,
    ) -> Optional[torch.FloatTensor]:
        """Grouped text-coordinate loss over the 0..999 coordinate distribution.

        The model still generates text digits, but this loss composes the three digit-token
        distributions into a single coordinate distribution for X/Y.  Targets are Gaussian
        around forward waypoints and uniform over equivalent padding regions for TURN/STOP.
        """
        if not self.use_coord_dist_aux_loss:
            return None
        if self.lambda_coord_dist <= 0 or self.coord_dist_sigma <= 0:
            return None

        digit_logits, target_xy = self._extract_coordinate_digit_logits_and_targets(shift_logits, shift_labels)
        if digit_logits is None or target_xy is None:
            return None

        cache = self._get_coordinate_value_tensors(shift_logits.device)
        values_float = cache['values_float']
        hundreds = cache['hundreds']
        tens = cache['tens']
        ones = cache['ones']

        digit_log_probs = F.log_softmax(digit_logits.float(), dim=-1)
        log_probs_x = (
            digit_log_probs[:, 0, hundreds]
            + digit_log_probs[:, 1, tens]
            + digit_log_probs[:, 2, ones]
        )
        log_probs_y = (
            digit_log_probs[:, 3, hundreds]
            + digit_log_probs[:, 4, tens]
            + digit_log_probs[:, 5, ones]
        )

        target_x = target_xy[:, 0]
        target_y = target_xy[:, 1]
        target_x_probs = self._gaussian_axis_targets(target_x, values_float, self.coord_dist_sigma)
        target_y_probs = self._gaussian_axis_targets(target_y, values_float, self.coord_dist_sigma)

        left_mask = target_x < self.coord_dist_left_max
        right_mask = target_x > self.coord_dist_right_min
        stop_mask = target_y > self.coord_dist_stop_min

        left_uniform = (values_float <= self.coord_dist_left_max).float()
        left_uniform = left_uniform / left_uniform.sum().clamp_min(1.0)
        right_uniform = (values_float >= self.coord_dist_right_min).float()
        right_uniform = right_uniform / right_uniform.sum().clamp_min(1.0)
        stop_uniform = (values_float >= self.coord_dist_stop_min).float()
        stop_uniform = stop_uniform / stop_uniform.sum().clamp_min(1.0)

        target_x_probs = torch.where(left_mask.view(-1, 1), left_uniform.view(1, -1), target_x_probs)
        target_x_probs = torch.where(right_mask.view(-1, 1), right_uniform.view(1, -1), target_x_probs)
        target_y_probs = torch.where(stop_mask.view(-1, 1), stop_uniform.view(1, -1), target_y_probs)

        loss_x = -(target_x_probs.to(log_probs_x.dtype) * log_probs_x).sum(dim=-1)
        loss_y = -(target_y_probs.to(log_probs_y.dtype) * log_probs_y).sum(dim=-1)
        return 0.5 * (loss_x + loss_y).mean()

    def _compute_angle_aux_loss(
            self,
            shift_logits: torch.FloatTensor,
            shift_labels: torch.LongTensor,
    ) -> Optional[torch.FloatTensor]:
        if not self.use_angle_aux_loss:
            return None
        if self.lambda_angle <= 0:
            return None

        pred_xy, target_xy = self._extract_soft_pred_and_target_coordinates(shift_logits, shift_labels)
        if pred_xy is None or target_xy is None:
            return None

        anchor = pred_xy.new_tensor([self.angle_anchor_x, self.angle_anchor_y])

        pred_dx = pred_xy[:, 0] - anchor[0]
        pred_dy = anchor[1] - pred_xy[:, 1]
        target_dx = target_xy[:, 0] - anchor[0]
        target_dy = anchor[1] - target_xy[:, 1]

        # Filter out STOP action: its coordinate (500, 999) coincides with the anchor, giving
        # target_dy ≈ 0 and target_dx ≈ 0.  atan2(0, 0) is ill-defined; the resulting
        # theta_gt = 0 rad (pointing right) is arbitrary and produces wrong gradients.
        # Any real navigation target is far from the anchor (dist >> 5 in [0,999] space).
        target_dist = target_dx.abs() + target_dy.abs()
        valid = target_dist > 5.0
        if not torch.any(valid):
            return None

        theta_pred = torch.atan2(pred_dy[valid], pred_dx[valid])
        theta_gt = torch.atan2(target_dy[valid], target_dx[valid])
        dtheta = theta_pred - theta_gt

        # Smooth, periodic angle loss: minimum when delta angle is 0 modulo 2pi.
        return (1.0 - torch.cos(dtheta)).mean()

    def _compute_action_hinge_aux_loss(
            self,
            shift_logits: torch.FloatTensor,
            shift_labels: torch.LongTensor,
    ) -> Optional[torch.FloatTensor]:
        """Forward-aware action-region hinge loss on soft expected coordinates.

        GT LEFT/RIGHT/STOP: enforce entering the corresponding special action region.
        GT FORWARD: enforce staying in RGB region and penalize entering any special region
        with larger multipliers (alpha_*).
        """
        if not self.use_action_hinge_aux_loss:
            return None
        if self.lambda_action_hinge <= 0:
            return None

        pred_xy, target_xy = self._extract_soft_pred_and_target_coordinates(shift_logits, shift_labels)
        if pred_xy is None or target_xy is None:
            return None

        pred_x = pred_xy[:, 0]
        pred_y = pred_xy[:, 1]
        target_x = target_xy[:, 0]
        target_y = target_xy[:, 1]

        left_max = float(self.action_hinge_left_max)
        right_min = float(self.action_hinge_right_min)
        stop_min = float(self.action_hinge_stop_min)

        gt_left = target_x < left_max
        gt_right = target_x > right_min
        gt_stop = target_y > stop_min
        gt_forward = ~(gt_left | gt_right | gt_stop)

        # Normalize hinge violations to coordinate range [0, 999] so per-sample loss
        # remains on a comparable 0..1 scale.
        coord_scale = pred_x.new_tensor(999.0)
        left_loss = F.relu(pred_x - left_max) / coord_scale
        right_loss = F.relu(right_min - pred_x) / coord_scale
        stop_loss = F.relu(stop_min - pred_y) / coord_scale

        fwd_left = self.action_hinge_forward_alpha_left * (F.relu(left_max - pred_x) / coord_scale)
        fwd_right = self.action_hinge_forward_alpha_right * (F.relu(pred_x - right_min) / coord_scale)
        fwd_stop = self.action_hinge_forward_alpha_stop * (F.relu(pred_y - stop_min) / coord_scale)
        alpha_sum = (
            self.action_hinge_forward_alpha_left
            + self.action_hinge_forward_alpha_right
            + self.action_hinge_forward_alpha_stop
        )
        alpha_denom = pred_x.new_tensor(max(float(alpha_sum), 1e-6))
        fwd_loss = (fwd_left + fwd_right + fwd_stop) / alpha_denom

        sample_loss = torch.zeros_like(pred_x)
        sample_loss = sample_loss + torch.where(gt_left, left_loss, sample_loss.new_zeros(()))
        sample_loss = sample_loss + torch.where(gt_right, right_loss, sample_loss.new_zeros(()))
        sample_loss = sample_loss + torch.where(gt_stop, stop_loss, sample_loss.new_zeros(()))
        sample_loss = sample_loss + torch.where(gt_forward, fwd_loss, sample_loss.new_zeros(()))
        return sample_loss.mean()

