    def _apply_visual_type_embeddings(self, vit_embeds: torch.FloatTensor, image_type_ids: Optional[torch.LongTensor]) -> torch.FloatTensor:
        """learnable embeeding to distinguish current image vs. history images"""
        if image_type_ids is None:
            return vit_embeds

        image_type_ids = image_type_ids.to(device=vit_embeds.device, dtype=torch.long)
        current = self.current_image_type_embedding.to(vit_embeds.dtype)
        history = self.history_image_type_embedding.to(vit_embeds.dtype)

        type_embeds = torch.where(
            image_type_ids.view(-1, 1) == 0,
            current.view(1, -1),
            history.view(1, -1),
        )
        return vit_embeds + type_embeds.unsqueeze(1)

    def _apply_history_temporal_sincos(
            self,
            vit_embeds: torch.FloatTensor,
            image_type_ids: Optional[torch.LongTensor],
    ) -> torch.FloatTensor:
        """Apply fixed sin/cos temporal encoding to history images only."""
        if not self.use_history_temporal_embeddings:
            return vit_embeds
        if image_type_ids is None:
            return vit_embeds
        if vit_embeds.numel() == 0:
            return vit_embeds

        image_type_ids = image_type_ids.to(device=vit_embeds.device, dtype=torch.long)
        history_mask = image_type_ids == 1
        if not torch.any(history_mask):
            return vit_embeds

        # Build per-image history position ids and reset after each current image.
        # This keeps packed samples independent, e.g. [0,1,1,0,1] -> [-1,0,1,-1,0].
        is_history = history_mask.to(dtype=torch.long)
        is_current = (image_type_ids == 0)
        positions = torch.arange(image_type_ids.numel(), device=vit_embeds.device)
        last_current_pos = torch.cummax(
            torch.where(is_current, positions, torch.full_like(positions, -1)),
            dim=0,
        ).values
        history_cumsum = torch.cumsum(is_history, dim=0)
        base_history_count = torch.where(
            last_current_pos >= 0,
            history_cumsum[last_current_pos.clamp_min(0)],
            torch.zeros_like(history_cumsum),
        )
        temporal_ids = history_cumsum - base_history_count - 1
        temporal_ids = torch.where(history_mask, temporal_ids, torch.full_like(temporal_ids, -1))

        history_temporal_ids = temporal_ids[history_mask]
        if history_temporal_ids.numel() == 0:
            return vit_embeds

        max_len = int(history_temporal_ids.max().item()) + 1
        hidden_size = vit_embeds.shape[-1]
        device = vit_embeds.device
        dtype = vit_embeds.dtype

        cache_key = (str(device), str(dtype), max_len, hidden_size)
        pe = self._history_temporal_pe_cache.get(cache_key)
        if pe is None:
            positions = torch.arange(max_len, device=device, dtype=torch.float32).unsqueeze(1)  # [T, 1]
            half_dim = hidden_size // 2
            if half_dim == 0:
                pe = torch.zeros(max_len, hidden_size, device=device, dtype=dtype)
            else:
                div_term = torch.exp(
                    torch.arange(half_dim, device=device, dtype=torch.float32)
                    * (-torch.log(torch.tensor(10000.0, device=device)) / hidden_size)
                )
                angles = positions * div_term.unsqueeze(0)
                pe = torch.zeros(max_len, hidden_size, device=device, dtype=torch.float32)
                pe[:, 0::2] = torch.sin(angles)
                pe[:, 1::2] = torch.cos(angles[:, : pe[:, 1::2].shape[1]])
                pe = pe.to(dtype=dtype)
            self._history_temporal_pe_cache[cache_key] = pe

        temporal_vectors = pe[history_temporal_ids]  # [N_history, D]
        alpha = self.history_temporal_alpha.to(dtype=vit_embeds.dtype, device=vit_embeds.device)

        updated = vit_embeds.clone()
        updated[history_mask] = updated[history_mask] + (alpha * temporal_vectors).unsqueeze(1)
        return updated

    def _apply_padding_region_embeddings(
            self,
            vit_embeds: torch.FloatTensor,
            image_type_ids: Optional[torch.LongTensor],
    ) -> torch.FloatTensor:
        if vit_embeds.numel() == 0:
            return vit_embeds
        if image_type_ids is None:
            return vit_embeds

        image_type_ids = image_type_ids.to(device=vit_embeds.device, dtype=torch.long)
        current_mask = image_type_ids == 0
        if not torch.any(current_mask):
            return vit_embeds

        updated = vit_embeds.clone()
        current_embeds = vit_embeds[current_mask]
        num_current_images, num_tokens, _ = current_embeds.shape

        padding_mask = torch.zeros((num_current_images, num_tokens), dtype=torch.bool, device=vit_embeds.device)
        grid_size = int(num_tokens ** 0.5)
        if grid_size * grid_size == num_tokens:
            if grid_size == 16:
                region_grid = torch.zeros((grid_size, grid_size), dtype=torch.bool, device=vit_embeds.device)
                # boundary tokens overlapping left/right/bottom padding are type=1.
                region_grid[:, 0] = True
                region_grid[:, -1] = True
                region_grid[-1, :] = True
                padding_mask = region_grid.reshape(1, -1).expand(num_current_images, -1).clone()
            else:
                logger.warning(f'Unexpected number of image tokens: {num_tokens}. Region embedding will not be applied.')

        # Full Embedding.forward() lookup so both rows have reachable gradient paths
        # when their ids appear in the batch.
        padding_ids = padding_mask.long()  # [num_current, num_tokens], values 0 or 1
        padding_embeds = self.padding_region_embedding(padding_ids).to(dtype=vit_embeds.dtype)
        updated[current_mask] = current_embeds + padding_embeds
        return updated

    def _apply_history_trajectory_embeddings(
            self,
            vit_embeds: torch.FloatTensor,
            image_type_ids: Optional[torch.LongTensor],
            history_traj_mask: Optional[torch.LongTensor],
    ) -> torch.FloatTensor:
        if not self.use_history_trajectory_embeddings:
            return vit_embeds
        if vit_embeds.numel() == 0:
            return vit_embeds
        if image_type_ids is None or history_traj_mask is None:
            return vit_embeds

        image_type_ids = image_type_ids.to(device=vit_embeds.device, dtype=torch.long)
        history_mask = image_type_ids == 1
        if not torch.any(history_mask):
            return vit_embeds

        history_traj_mask = history_traj_mask.to(device=vit_embeds.device, dtype=torch.long)
        if history_traj_mask.dim() == 3:
            history_traj_mask = history_traj_mask.squeeze(0)
        if history_traj_mask.dim() != 2:
            logger.warning(f'历史轨迹 mask 维度异常: {history_traj_mask.shape}，跳过历史轨迹嵌入。')
            return vit_embeds
        if history_traj_mask.size(0) != vit_embeds.size(0) or history_traj_mask.size(1) != vit_embeds.size(1):
            logger.warning(
                f'历史轨迹 mask 形状不匹配: mask={history_traj_mask.shape}, vit={vit_embeds.shape[:2]}，跳过历史轨迹嵌入。'
            )
            return vit_embeds

        history_mask_2d = history_mask.unsqueeze(1).expand(-1, vit_embeds.size(1))
        traj_token_mask = history_mask_2d & (history_traj_mask > 0)
        if not torch.any(traj_token_mask):
            return vit_embeds

        # Apply embedding only on trajectory tokens; keep common tokens unchanged.
        traj_vector = self.history_trajectory_embedding.weight[1].to(dtype=vit_embeds.dtype)
        traj_delta = traj_token_mask.unsqueeze(-1).to(dtype=vit_embeds.dtype) * traj_vector.view(1, 1, -1)
        return vit_embeds + traj_delta

    # =============== Forward ================
    def forward(
            self,
            pixel_values: torch.FloatTensor,
            input_ids: torch.LongTensor = None,
            attention_mask: Optional[torch.Tensor] = None,
            position_ids: Optional[torch.LongTensor] = None,
            image_flags: Optional[torch.LongTensor] = None,
            image_type_ids: Optional[torch.LongTensor] = None,  # [image number], 0 for current image, 1 for history image for data
            history_traj_mask: Optional[torch.LongTensor] = None,  # [image number, num_image_token], 1 with trajectory, 0 without trajectory
            past_key_values: Optional[List[torch.FloatTensor]] = None,
            labels: Optional[torch.LongTensor] = None,
            use_cache: Optional[bool] = None,
            output_attentions: Optional[bool] = None,
            output_hidden_states: Optional[bool] = None,
            return_dict: Optional[bool] = None,
            statistics: Optional[torch.LongTensor] = None,
            loss_weight: Optional[List] = None,
            loss_reduction_all_gather: Optional[bool] = False,
    ) -> Union[Tuple, CausalLMOutputWithPast]:
        return_dict = return_dict if return_dict is not None else self.config.use_return_dict

        image_flags = image_flags.squeeze(-1)
        input_embeds = self.language_model.get_input_embeddings()(input_ids).clone()

        vit_embeds = self.extract_feature(pixel_values)
        vit_embeds = vit_embeds[image_flags == 1]
        selected_image_type_ids = None
        if image_type_ids is not None:
            image_type_ids = image_type_ids.squeeze(-1) if image_type_ids.dim() > 1 else image_type_ids
            selected_image_type_ids = image_type_ids[image_flags == 1]
        selected_history_traj_mask = None
        if history_traj_mask is not None:
            selected_history_traj_mask = history_traj_mask[image_flags == 1]
        if self.use_image_type_embeddings and selected_image_type_ids is not None:
            vit_embeds = self._apply_visual_type_embeddings(vit_embeds, selected_image_type_ids)
        if self.use_history_temporal_embeddings and selected_image_type_ids is not None:
            vit_embeds = self._apply_history_temporal_sincos(vit_embeds, selected_image_type_ids)
        if self.use_padding_embeddings and selected_image_type_ids is not None:
            vit_embeds = self._apply_padding_region_embeddings(vit_embeds, selected_image_type_ids)
        if self.use_history_trajectory_embeddings and selected_image_type_ids is not None and selected_history_traj_mask is not None:
            vit_embeds = self._apply_history_trajectory_embeddings(vit_embeds, selected_image_type_ids, selected_history_traj_mask)
        vit_batch_size = pixel_values.shape[0]

        B, N, C = input_embeds.shape
        input_embeds = input_embeds.reshape(B * N, C)

        if torch.distributed.is_initialized() and torch.distributed.get_rank() == 0:
            # print(f'dynamic ViT batch size: {v it_batch_size}, images per sample: {vit_batch_size / B}, dynamic token length: {N}')
            if statistics is not None:
                num_samples, num_padding_tokens, num_padding_images = statistics.tolist()
                self.num_samples += num_samples
                # print(f'total_samples={self.num_samples}, {num_samples=}, {num_padding_tokens=}, {num_padding_images=}')

        input_ids = input_ids.reshape(B * N)
        selected = (input_ids == self.img_context_token_id)
        try:
            input_embeds[selected] = input_embeds[selected] * 0.0 + vit_embeds.reshape(-1, C)
            ignore_flag = False
        except Exception as e:
            vit_embeds = vit_embeds.reshape(-1, C)
            print(f'warning: {e}, input_embeds[selected].shape={input_embeds[selected].shape}, '
                  f'vit_embeds.shape={vit_embeds.shape}')
            n_token = selected.sum()
            input_embeds[selected] = input_embeds[selected] * 0.0 + vit_embeds[:n_token]
            ignore_flag = True

        input_embeds = input_embeds.reshape(B, N, C)

        outputs = self.language_model(
            inputs_embeds=input_embeds,
            attention_mask=attention_mask,
            position_ids=position_ids,
            past_key_values=past_key_values,
            use_cache=use_cache,
            output_attentions=output_attentions,
            output_hidden_states=output_hidden_states,
            return_dict=return_dict,
        )
        logits = outputs.logits

        loss = None
        if labels is not None and loss_weight is not None:
            if torch.is_tensor(loss_weight):
                loss_weight = loss_weight.to(device=labels.device, dtype=torch.float32)
            else:
                loss_weight = torch.as_tensor(loss_weight, dtype=torch.float32, device=labels.device)
            # Shift so that tokens < n predict n
            shift_logits = logits[..., :-1, :].contiguous()
            shift_labels = labels[..., 1:].contiguous()
            shift_weights = loss_weight[..., 1:].contiguous()
            # numeric auxiliary loss
            numeric_loss = None
            angle_loss = None
            coord_dist_loss = None
            action_hinge_loss = None
            if self.training and self.use_numeric_aux_loss and self.lambda_num > 0:
                numeric_loss = self._compute_numeric_aux_loss(shift_logits, shift_labels)
            if self.training and self.use_angle_aux_loss and self.lambda_angle > 0:
                angle_loss = self._compute_angle_aux_loss(shift_logits, shift_labels)
            if self.training and self.use_coord_dist_aux_loss and self.lambda_coord_dist > 0:
                coord_dist_loss = self._compute_coord_dist_aux_loss(shift_logits, shift_labels)
            if self.training and self.use_action_hinge_aux_loss and self.lambda_action_hinge > 0:
                action_hinge_loss = self._compute_action_hinge_aux_loss(shift_logits, shift_labels)
            shift_logits = shift_logits.view(-1, self.language_model.config.vocab_size)
            shift_labels = shift_labels.view(-1)
            shift_weights = shift_weights.view(-1)
            # Enable model parallelism
            shift_labels = shift_labels.to(shift_logits.device)
            shift_weights = shift_weights.to(shift_logits.device)
            loss_fct = CrossEntropyLoss(reduction='none')
            loss_vec = loss_fct(shift_logits, shift_labels)
            valid_mask = shift_labels != -100
            weighted_loss_sum = (loss_vec[valid_mask] * shift_weights[valid_mask]).sum() if torch.any(valid_mask) else shift_logits.new_zeros(())
            shift_weights_sum = shift_weights[valid_mask].sum() if torch.any(valid_mask) else shift_weights.new_zeros(())

            if loss_reduction_all_gather:
                dist.all_reduce(shift_weights_sum, op=dist.ReduceOp.AVG)
            shift_weights_sum = shift_weights_sum.clamp_min(1e-6)

            loss = weighted_loss_sum / shift_weights_sum
            if ignore_flag:
                # Vision/text shape mismatch: CE is zeroed AND aux losses must be skipped,
                # otherwise numeric/angle (computed from the same suspect logits) keep injecting bad gradients.
                loss = loss * 0.0
            else:
                if numeric_loss is not None:
                    loss = loss + self.lambda_num * numeric_loss
                if angle_loss is not None:
                    loss = loss + self.lambda_angle * angle_loss
                if coord_dist_loss is not None:
                    loss = loss + self.lambda_coord_dist * coord_dist_loss
                if action_hinge_loss is not None:
                    loss = loss + self.lambda_action_hinge * action_hinge_loss
        elif labels is not None:
            # Shift so that tokens < n predict n
            shift_logits = logits[..., :-1, :].contiguous()
            shift_labels = labels[..., 1:].contiguous()
            numeric_loss = None
            angle_loss = None
            coord_dist_loss = None
            action_hinge_loss = None
            if self.training and self.use_numeric_aux_loss and self.lambda_num > 0:
                numeric_loss = self._compute_numeric_aux_loss(shift_logits, shift_labels)
            if self.training and self.use_angle_aux_loss and self.lambda_angle > 0:
                angle_loss = self._compute_angle_aux_loss(shift_logits, shift_labels)
            if self.training and self.use_coord_dist_aux_loss and self.lambda_coord_dist > 0:
                coord_dist_loss = self._compute_coord_dist_aux_loss(shift_logits, shift_labels)
            if self.training and self.use_action_hinge_aux_loss and self.lambda_action_hinge > 0:
                action_hinge_loss = self._compute_action_hinge_aux_loss(shift_logits, shift_labels)
            shift_logits = shift_logits.view(-1, self.language_model.config.vocab_size)
            shift_labels = shift_labels.view(-1)
            # Enable model parallelism
            shift_labels = shift_labels.to(shift_logits.device)
            loss_fct = CrossEntropyLoss(reduction='none')
            loss_vec = loss_fct(shift_logits, shift_labels)
            valid_mask = shift_labels != -100
            loss = loss_vec[valid_mask].mean() if torch.any(valid_mask) else shift_logits.new_zeros(())
            if ignore_flag:
                loss = loss * 0.0
            else:
                if numeric_loss is not None:
                    loss = loss + self.lambda_num * numeric_loss
                if angle_loss is not None:
                    loss = loss + self.lambda_angle * angle_loss
                if coord_dist_loss is not None:
                    loss = loss + self.lambda_coord_dist * coord_dist_loss
                if action_hinge_loss is not None:
                    loss = loss + self.lambda_action_hinge * action_hinge_loss

        if not return_dict:
            output = (logits,) + outputs[1:]
            return (loss,) + output if loss is not None else output

        return CausalLMOutputWithPast(
            loss=loss,
            logits=logits,
            past_key_values=outputs.past_key_values,
            hidden_states=outputs.hidden_states,
            attentions=outputs.attentions,
        )

    def pixel_shuffle(self, x, scale_factor=0.5):
        n, w, h, c = x.size()
        # N, W, H, C --> N, W, H * scale, C // scale
        x = x.view(n, w, int(h * scale_factor), int(c / scale_factor))
        # N, W, H * scale, C // scale --> N, H * scale, W, C // scale
        x = x.permute(0, 2, 1, 3).contiguous()
        # N, H * scale, W, C // scale --> N, H * scale, W * scale, C // (scale ** 2)
        x = x.view(n, int(h * scale_factor), int(w * scale_factor),
                   int(c / (scale_factor * scale_factor)))
        if self.ps_version == 'v1':
            warnings.warn("In ps_version 'v1', the height and width have not been swapped back, "
                          'which results in a transposed image.')
        else:
            x = x.permute(0, 2, 1, 3).contiguous()
        return x

    def extract_feature(self, pixel_values):
        if self.select_layer == -1:
            vit_embeds = self.vision_model(
                pixel_values=pixel_values,
                output_hidden_states=False,
                return_dict=True).last_hidden_state
        else:
            vit_embeds = self.vision_model(
                pixel_values=pixel_values,
                output_hidden_states=True,
                return_dict=True).hidden_states[self.select_layer]
        vit_embeds = vit_embeds[:, 1:, :]

        h = w = int(vit_embeds.shape[1] ** 0.5)
        vit_embeds = vit_embeds.reshape(vit_embeds.shape[0], h, w, -1)
        vit_embeds = self.pixel_shuffle(vit_embeds, scale_factor=self.downsample_ratio)
        vit_embeds = vit_embeds.reshape(vit_embeds.shape[0], -1, vit_embeds.shape[-1])
        vit_embeds = self.mlp1(vit_embeds)
        return vit_embeds

    def batch_chat(self, tokenizer, pixel_values, questions, generation_config, num_patches_list=None,
                   history=None, return_history=False, IMG_START_TOKEN='<img>', IMG_END_TOKEN='</img>',
                   IMG_CONTEXT_TOKEN='<IMG_CONTEXT>', verbose=False, image_counts=None):
        if history is not None or return_history:
            print('Now multi-turn chat is not supported in batch_chat.')
            raise NotImplementedError

        if image_counts is not None:
            num_patches_list = image_counts
            print('Warning: `image_counts` is deprecated. Please use `num_patches_list` instead.')

        img_context_token_id = tokenizer.convert_tokens_to_ids(IMG_CONTEXT_TOKEN)
        self.img_context_token_id = img_context_token_id

        if verbose and pixel_values is not None:
            image_bs = pixel_values.shape[0]
            # print(f'dynamic ViT batch size: {image_bs}')

        queries = []
        for idx, num_patches in enumerate(num_patches_list):
            question = questions[idx]
            if pixel_values is not None and '<image>' not in question:
                question = '<image>\n' + question
            template = get_conv_template(self.template)
            template.system_message = self.system_message
            template.append_message(template.roles[0], question)
            template.append_message(template.roles[1], None)
            query = template.get_prompt()

            image_tokens = IMG_START_TOKEN + IMG_CONTEXT_TOKEN * self.num_image_token * num_patches + IMG_END_TOKEN
            query = query.replace('<image>', image_tokens, 1)
            queries.append(query)

        tokenizer.padding_side = 'left'
        model_inputs = tokenizer(queries, return_tensors='pt', padding=True)
        device = torch.device(self.language_model.device if torch.cuda.is_available() else 'cpu')
        input_ids = model_inputs['input_ids'].to(device)
        attention_mask = model_inputs['attention_mask'].to(device)
        eos_token_id = tokenizer.convert_tokens_to_ids(template.sep.strip())
        generation_config['eos_token_id'] = eos_token_id
        generation_output = self.generate(
            pixel_values=pixel_values,
            input_ids=input_ids,
            attention_mask=attention_mask,
            **generation_config
        )
        responses = tokenizer.batch_decode(generation_output, skip_special_tokens=True)
        responses = [response.split(template.sep.strip())[0].strip() for response in responses]
        return responses

    def chat(self, tokenizer, pixel_values, question, generation_config, history=None, return_history=False,
             num_patches_list=None, IMG_START_TOKEN='<img>', IMG_END_TOKEN='</img>', IMG_CONTEXT_TOKEN='<IMG_CONTEXT>',
             verbose=False, history_traj_mask: Optional[torch.LongTensor] = None):

        if history is None and pixel_values is not None and '<image>' not in question:
            question = '<image>\n' + question

        if num_patches_list is None:
            num_patches_list = [pixel_values.shape[0]] if pixel_values is not None else []
        assert pixel_values is None or len(pixel_values) == sum(num_patches_list)

        if pixel_values is not None:
            # Follow training semantics: first logical image is current (0), rest are history (1),
            # then expand to patch-level ids according to num_patches_list.
            logical_types = [0] + [1] * (len(num_patches_list) - 1)
            expanded_types = []
            for img_type, n_patches in zip(logical_types, num_patches_list):
                expanded_types.extend([img_type] * int(n_patches))
            image_type_ids = torch.as_tensor(expanded_types, dtype=torch.long)

        img_context_token_id = tokenizer.convert_tokens_to_ids(IMG_CONTEXT_TOKEN)
        self.img_context_token_id = img_context_token_id

        template = get_conv_template(self.template)
        template.system_message = self.system_message
        eos_token_id = tokenizer.convert_tokens_to_ids(template.sep.strip())

        history = [] if history is None else history
        for (old_question, old_answer) in history:
            template.append_message(template.roles[0], old_question)
            template.append_message(template.roles[1], old_answer)
        template.append_message(template.roles[0], question)
        template.append_message(template.roles[1], None)
        query = template.get_prompt()

        if verbose and pixel_values is not None:
            image_bs = pixel_values.shape[0]
            # print(f'dynamic ViT batch size: {image_bs}')

        for num_patches in num_patches_list:
            image_tokens = IMG_START_TOKEN + IMG_CONTEXT_TOKEN * self.num_image_token * num_patches + IMG_END_TOKEN
            query = query.replace('<image>', image_tokens, 1)

        model_inputs = tokenizer(query, return_tensors='pt')
        device = torch.device(self.language_model.device if torch.cuda.is_available() else 'cpu')
        input_ids = model_inputs['input_ids'].to(device)
        attention_mask = model_inputs['attention_mask'].to(device)
        generation_config['eos_token_id'] = eos_token_id
        generation_output = self.generate(
            pixel_values=pixel_values,
            input_ids=input_ids,
            attention_mask=attention_mask,
            image_type_ids=image_type_ids,
            history_traj_mask=history_traj_mask,
            **generation_config
        )
        response = tokenizer.batch_decode(generation_output, skip_special_tokens=True)[0]
        response = response.split(template.sep.strip())[0].strip()
        history.append((question, response))
        if return_history:
            return response, history
        else:
            query_to_print = query.replace(IMG_CONTEXT_TOKEN, '')
            query_to_print = query_to_print.replace(f'{IMG_START_TOKEN}{IMG_END_TOKEN}', '<image>')
            if verbose:
                print(query_to_print, response)
            return response

    @torch.no_grad()
    def generate(
            self,
            pixel_values: Optional[torch.FloatTensor] = None,
            input_ids: Optional[torch.FloatTensor] = None,
            attention_mask: Optional[torch.LongTensor] = None,
            image_type_ids: Optional[torch.LongTensor] = None,
            history_traj_mask: Optional[torch.LongTensor] = None,
            visual_features: Optional[torch.FloatTensor] = None,
            generation_config: Optional[GenerationConfig] = None,
            output_hidden_states: Optional[bool] = None,
            **generate_kwargs,
    ) -> torch.LongTensor:

        assert self.img_context_token_id is not None
        if pixel_values is not None:
            if visual_features is not None:
                vit_embeds = visual_features
            else:
                vit_embeds = self.extract_feature(pixel_values)
            if image_type_ids is not None:
                image_type_ids = image_type_ids.squeeze(-1) if image_type_ids.dim() > 1 else image_type_ids
            if self.use_image_type_embeddings and image_type_ids is not None:
                vit_embeds = self._apply_visual_type_embeddings(vit_embeds, image_type_ids)
            if self.use_history_temporal_embeddings and image_type_ids is not None:
                vit_embeds = self._apply_history_temporal_sincos(vit_embeds, image_type_ids)
            if self.use_padding_embeddings and image_type_ids is not None:
                vit_embeds = self._apply_padding_region_embeddings(vit_embeds, image_type_ids)
            if self.use_history_trajectory_embeddings and image_type_ids is not None and history_traj_mask is not None:
                vit_embeds = self._apply_history_trajectory_embeddings(vit_embeds, image_type_ids, history_traj_mask)

            input_embeds = self.language_model.get_input_embeddings()(input_ids)
            B, N, C = input_embeds.shape
            input_embeds = input_embeds.reshape(B * N, C)

            input_ids = input_ids.reshape(B * N)
            selected = (input_ids == self.img_context_token_id)
            assert selected.sum() != 0
            input_embeds[selected] = vit_embeds.reshape(-1, C).to(input_embeds.device)

            input_embeds = input_embeds.reshape(B, N, C)
        else:
            input_embeds = self.language_model.get_input_embeddings()(input_ids)

        outputs = self.language_model.generate(
            inputs_embeds=input_embeds,
            attention_mask=attention_mask,
            generation_config=generation_config,
            output_hidden_states=output_hidden_states,
            use_cache=True,
            **generate_kwargs,
        )

        return outputs

    @property
    def lm_head(self):
        return self.language_model.get_output_embeddings()

    def get_input_embeddings(self):
        return self.language_model.get_input_embeddings()

    def get_output_embeddings(self):
        return self.language_model.get_output_embeddings()
        
